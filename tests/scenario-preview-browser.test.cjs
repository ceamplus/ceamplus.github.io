const assert = require('node:assert/strict');
const fs = require('node:fs');
const crypto = require('node:crypto');
const {chromium} = require(process.env.CEAM_PLAYWRIGHT_PATH || 'playwright');
const base = process.env.CEAM_TEST_URL || 'http://127.0.0.1:8765';
(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
    const page = await context.newPage();
    const requests=[], errors=[];
    page.on('request',r=>requests.push(r.url()));
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base+'/scenario-studio-preview.html');
    await page.evaluate(()=>{localStorage.setItem('ceamplus.assessment-center.v1','{"fixture":"unchanged saved result"}');localStorage.setItem('ceamplus.personas.custom.v1','{"fixture":"unchanged persona"}');});
    const storage = () => page.evaluate(()=>JSON.stringify(Object.entries(localStorage).sort()));
    const before = await storage();
    assert.equal(await page.locator('h1').innerText(),'Scenario Studio');
    assert.equal(await page.locator('.preview-path-grid details').count(),6);
    assert.equal(await page.locator('.preview-step').count(),14);
    assert.equal(await page.locator('form,input,textarea,video,iframe').count(),0);
    assert.match(await page.locator('main').innerText(),/Not a validated prediction system/);
    assert.match(await page.locator('.preview-video-placeholder').innerText(),/no finished video is available/);
    assert.match(await page.locator('.preview-video-placeholder').innerText(),/written walkthrough is currently available/);
    assert.match(await page.locator('.preview-case').innerText(),/All example information is fictional/);
    assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior),'auto');
    await page.locator('.nav-more summary').focus();
    await page.keyboard.press('Enter');
    assert(await page.locator('.nav-more').evaluate(e=>e.open));
    assert(await page.locator('nav.nav-links a[aria-current=page]').isVisible());
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.nav-more').evaluate(e=>e.open),false);
    const first = page.locator('.preview-path-grid summary').first();
    await first.focus();await page.keyboard.press('Enter');
    assert(await page.locator('.preview-path-grid details').first().evaluate(e=>e.open));
    await page.locator('#preview-next').click();
    assert.equal(await page.locator('#preview-step-status').innerText(),'Step 2 of 14');
    assert(await page.locator('.preview-step').nth(1).evaluate(e=>e.open));
    await page.locator('#preview-previous').click();
    assert.equal(await page.locator('#preview-step-status').innerText(),'Step 1 of 14');
    await page.locator('#video-transcript summary').click();
    assert(await page.locator('.preview-transcript').isVisible());
    assert.equal(await storage(),before);
    const links=await page.locator('a[href]').evaluateAll(a=>a.map(e=>e.getAttribute('href')));
    for(const href of [...new Set(links)]) {
      if(href.startsWith('#'))assert.equal(await page.locator('[id="'+href.slice(1)+'"]').count(),1,href);
      else if(!/^[a-z]+:/i.test(href))assert.equal((await page.request.get(base+'/'+href)).status(),200,href);
    }
    assert(!requests.some(u=>u.includes('/js/scenario-studio/')||u.includes('calculation-provenance')||!u.startsWith(base)),requests.join('\n'));
    assert.deepEqual(errors,[]);
    for(const width of [320,390,768,1024,1440]) {
      await page.setViewportSize({width,height:1000});
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'overflow '+width);
      await page.locator('.nav-more summary').click();
      const box=await page.locator('.nav-secondary').boundingBox();assert(box.x>=0&&box.x+box.width<=width+1);
      await page.keyboard.press('Escape');
    }
    await page.reload();
    await page.setViewportSize({width:1440,height:1000});
    fs.mkdirSync('.cache/preview-verification',{recursive:true});
    await page.screenshot({path:'.cache/preview-verification/desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'.cache/preview-verification/mobile.png',fullPage:true});
    const noJS=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
    const fallback=await noJS.newPage();await fallback.goto(base+'/scenario-studio-preview.html');
    await fallback.locator('.preview-path-grid summary').first().click();
    assert(await fallback.locator('.preview-path-grid details').first().evaluate(e=>e.open));
    assert(await fallback.locator('.preview-step').first().isVisible());
    assert(await fallback.locator('.preview-step-controls').isHidden());
    assert.equal(await fallback.locator('.preview-choice-buttons:visible').count(),0);
    assert.match(await fallback.locator('#marketing-example').innerText(),/25 purchases \(sales count\)/);
    assert.match(await fallback.locator('#research-example').innerText(),/96 completed responses/);
    const staticMarketing = await fallback.locator('#marketing-projection').innerText();
    const staticResearch = await fallback.locator('#research-projection').innerText();
    await noJS.close();
    const source = fs.readFileSync('scenario-studio-preview.html','utf8');
    const script = fs.readFileSync('js/scenario-preview.js','utf8');
    const poster = fs.readFileSync('assets/video/scenario-preview-poster.svg','utf8');
    assert(!source.includes('ceam-icon.jpeg'),'new preview uses a text brand without adding an unresolved image dependency');
    assert(!/[—]/.test(source + script + poster));
    assert(!/import\s|fetch\s*\(|localStorage|sessionStorage|indexedDB|XMLHttpRequest/.test(script));
    assert.deepEqual(await page.locator('.preview-path-grid summary').evaluateAll(es=>es.map(e=>e.textContent.replace(/^\d+/, '').trim())), ['Baseline','Conservative case','Target case','Alternative strategy','Stress case','Custom scenario']);
    assert.match(await page.locator('.preview-hero').innerText(), /Explore marketing and research possibilities before committing/);
    assert(!/\bAI\b|automation|delegat/i.test(await page.locator('.preview-hero,.preview-path-grid').allInnerTexts().then(x=>x.join(' '))));
    for (const id of ['marketing-example','research-example']) assert.match(await page.locator('#'+id).innerText(), /[Ff]ictional/);
    assert.match(source,/No likelihood is assigned/);
    assert.match(source,/Percentiles require a justified distribution or model/);
    assert.match(source,/neither a forecast nor a prediction/);
    assert.equal(await page.locator('#marketing-example tbody tr').count(),6);
    assert.equal(await page.locator('#research-example tbody tr').count(),6);
    const marketingCopy = await page.locator('#marketing-example').innerText();
    const researchCopy = await page.locator('#research-example').innerText();
    assert.match(marketingCopy,/lead qualification is not modeled here/);
    assert.match(marketingCopy,/purchases \(sales count\) = responses × purchase-conversion rate/);
    assert.match(marketingCopy,/revenue = purchases × average revenue per purchase/);
    assert.match(researchCopy,/survey starts = invitations × survey-start rate/);
    assert.match(researchCopy,/completed responses = survey starts × completion rate/);
    assert.match(researchCopy,/Completed responses are not automatically usable responses or retained participants/);
    assert(!/retained survey response|20% attrition|initial response/.test(source));
    assert.match(poster,/50 purchases/);
    assert.match(poster,/80% of starts complete/);
    assert.match(poster,/Usability and later retention are not modeled/);
    await page.locator('#video-transcript summary').click();
    const narration = await page.locator('.preview-transcript').innerText();
    assert.match(narration,/two hundred responses/);
    assert.match(narration,/fifty purchases, also called the sales count/);
    assert.match(narration,/one hundred twenty start and ninety-six complete/);
    assert.match(narration,/Usability, later retention and later attrition are not modeled/);
    await page.locator('[data-marketing-response="1"]').click();
    assert.match(await page.locator('#marketing-projection').innerText(),/100 responses; 25 purchases \(sales count\); \$3,000 revenue; \$0 contribution/);
    assert.equal(await page.locator('[data-marketing-response="1"]').getAttribute('aria-pressed'),'true');
    await page.locator('[data-marketing-response="2"]').click();
    assert.equal(await page.locator('#marketing-projection').innerText(),staticMarketing);
    assert.equal(await page.locator('[data-marketing-response="1"]').getAttribute('aria-pressed'),'false');
    await page.locator('[data-research-start="15"]').click();
    assert.match(await page.locator('#research-projection').innerText(),/120 survey starts; 96 completed responses; \$1,360/);
    assert.equal(await page.locator('[data-research-start="15"]').getAttribute('aria-pressed'),'true');
    await page.locator('[data-research-start="25"]').click();
    assert.equal(await page.locator('#research-projection').innerText(),staticResearch);
    assert.equal(await page.locator('[data-research-start="15"]').getAttribute('aria-pressed'),'false');
    assert.equal(await storage(),before);
    const backgrounds=await page.locator('.preview-path-grid details').evaluateAll(es=>es.map(e=>[getComputedStyle(e).backgroundColor,getComputedStyle(e).borderColor].join('|')));
    assert.equal(new Set(backgrounds).size,1);
    const baselinePath=fs.existsSync('.cache/survey-retirement/before.json')?'.cache/survey-retirement/before.json':'.cache/scenario-preview-review/reframe-baseline.json';
    let protectedCount=0;
    if(fs.existsSync(baselinePath)) {
      const original=JSON.parse(fs.readFileSync(baselinePath));
      const protectedFiles=Object.keys(original).filter(p=>p!=='./js/assessments/app.mjs').filter(p=>p.endsWith('/LICENSE')||p.includes('/assets/vendor/')||p.includes('/js/assessments/')||p.includes('/js/personas/')||p.includes('/js/scenario-studio/')||p.includes('/docs/legal/')||p.includes('/docs/strategy/'));
      for(const p of protectedFiles) assert.equal(crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex'),original[p],p);
      protectedCount=protectedFiles.length;
    }
    console.log('PASS preview: links, 14 steps, keyboard, reduced motion, no-JS fallback, five widths, isolated requests/storage and '+protectedCount+' protected sources; desktop/mobile screenshots saved');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
